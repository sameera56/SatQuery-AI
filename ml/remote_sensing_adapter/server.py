"""SATQUERY remote-sensing adapter inference service.

This service loads the BigEarthNet-adapted CLIP checkpoint produced by train.py
and returns auditable, query-conditioned image evidence. It deliberately reports
"unavailable" instead of silently substituting a generic vision model when no
adapted checkpoint exists.
"""
from __future__ import annotations

import base64
import io
import os
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Any

import open_clip
import torch
from fastapi import FastAPI, HTTPException
from PIL import Image, ImageDraw
from pydantic import BaseModel, Field


class AnalyzeRequest(BaseModel):
    query: str = Field(min_length=1, max_length=500)
    mode: str = Field(pattern="^(optical|sar|optical-sar|bi-temporal)$")
    images: list[str] = Field(min_length=1, max_length=2)


class RasterValidationRequest(BaseModel):
    mode: str = Field(pattern="^(optical-sar|bi-temporal)$")
    images: list[str] = Field(min_length=2, max_length=2)


model: Any = None
preprocess: Any = None
tokenizer: Any = None
device = "cpu"
checkpoint_path = ""
load_error: str | None = None
checkpoint_metadata: dict[str, Any] = {}

LABELS = {
    "optical": ["open water", "flooded land", "built-up area", "road network", "cropland", "forest vegetation", "bare soil", "cloud cover"],
    "sar": ["smooth water surface", "rough urban surface", "vegetation texture", "bare ground", "linear infrastructure"],
    "optical-sar": ["water-covered area", "built-up area", "vegetated land", "transport corridor", "bare soil"],
    "bi-temporal": ["water extent", "built-up area", "vegetation cover", "bare soil", "transport infrastructure"],
}


@asynccontextmanager
async def lifespan(_: FastAPI):
    global model, preprocess, tokenizer, device, checkpoint_path, load_error, checkpoint_metadata
    checkpoint_path = os.getenv("SATQUERY_ADAPTER_CHECKPOINT", "/models/bigearthnet-clip-adapter.pt")
    try:
        if not Path(checkpoint_path).is_file():
            load_error = f"Adapted checkpoint not found at {checkpoint_path}"
            yield
            return
        device = "cuda" if torch.cuda.is_available() and os.getenv("SATQUERY_ADAPTER_DEVICE", "cuda") != "cpu" else "cpu"
        checkpoint = torch.load(checkpoint_path, map_location=device, weights_only=False)
        base_model = checkpoint.get("base_model", "ViT-B-32")
        model, _, preprocess = open_clip.create_model_and_transforms(base_model, pretrained=None)
        model.load_state_dict(checkpoint["state_dict"], strict=True)
        model.to(device).eval()
        tokenizer = open_clip.get_tokenizer(base_model)
        checkpoint_metadata = {key: checkpoint.get(key) for key in ("base_model", "manifest_sha256", "samples", "epochs", "trained_at")}
    except Exception as exc:  # Never start a fake "ready" service.
        model = None
        load_error = str(exc)
    yield
    model = None


app = FastAPI(title="SATQUERY Remote-Sensing Adapter", lifespan=lifespan)


def decode_image(data: str) -> Image.Image:
    try:
        return Image.open(io.BytesIO(base64.b64decode(data))).convert("RGB")
    except Exception as exc:
        raise HTTPException(status_code=400, detail="One supplied image could not be decoded.") from exc


@app.get("/health")
def health():
    return {
        "ready": model is not None,
        "engine": "bigearthnet-adapted-clip" if model is not None else None,
        "device": device if model is not None else None,
        "checkpoint": checkpoint_path if model is not None else None,
        "changeMask": model is not None,
        "geoValidator": _has_rasterio(),
        "reason": load_error,
        "training": checkpoint_metadata if model is not None else None,
    }


def _has_rasterio() -> bool:
    try:
        import rasterio  # noqa: F401
        return True
    except ImportError:
        return False


def semantic_change_heatmap(first: Image.Image, second: Image.Image) -> dict[str, Any]:
    """Generate a coarse, model-derived change heatmap from aligned input pairs.

    This is deliberately reported as a semantic heatmap, not a survey-grade
    segmentation mask: it is generated by comparing grid-cell embeddings from
    the trained BigEarthNet adapter and must not be used for area measurement
    without validated georegistration and a task-trained segmentation model.
    """
    grid, size = 8, 256
    first, second = first.resize((size, size)), second.resize((size, size))
    tile = size // grid
    crops = []
    for image in (first, second):
        for row in range(grid):
            for column in range(grid):
                crops.append(preprocess(image.crop((column * tile, row * tile, (column + 1) * tile, (row + 1) * tile))).unsqueeze(0))
    with torch.no_grad():
        embeddings = model.encode_image(torch.cat(crops).to(device))
        embeddings = embeddings / embeddings.norm(dim=-1, keepdim=True)
        difference = 1 - torch.nn.functional.cosine_similarity(embeddings[: grid * grid], embeddings[grid * grid:])
    threshold = float((difference.mean() + 0.5 * difference.std()).item())
    maximum = max(float(difference.max().item()), 1e-6)
    heatmap = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(heatmap)
    changed = 0
    for index, score in enumerate(difference.detach().cpu().tolist()):
        if score < threshold:
            continue
        changed += 1
        intensity = int(min(255, max(80, score / maximum * 255)))
        row, column = divmod(index, grid)
        draw.rectangle((column * tile, row * tile, (column + 1) * tile - 1, (row + 1) * tile - 1), fill=(255, 59, 48, intensity))
    out = io.BytesIO()
    heatmap.save(out, format="PNG")
    return {
        "kind": "adapter-semantic-change-heatmap",
        "image": base64.b64encode(out.getvalue()).decode("ascii"),
        "width": size,
        "height": size,
        "grid": grid,
        "threshold": round(threshold, 4),
        "changedCells": changed,
        "totalCells": grid * grid,
        "limitation": "Coarse semantic heatmap from the adapted encoder; it is not a pixel-accurate change mask and cannot support area measurement without a validated segmentation model and GeoTIFF registration.",
    }


@app.post("/validate-raster")
def validate_raster(request: RasterValidationRequest):
    if not _has_rasterio():
        raise HTTPException(status_code=503, detail="GeoTIFF validator is unavailable; install rasterio in the adapter service.")
    import rasterio
    from rasterio.io import MemoryFile

    records = []
    for encoded in request.images:
        try:
            with MemoryFile(base64.b64decode(encoded)) as memory:
                with memory.open() as dataset:
                    records.append({
                        "crs": str(dataset.crs) if dataset.crs else None,
                        "bounds": [round(float(value), 8) for value in dataset.bounds],
                        "resolution": [round(float(value), 8) for value in dataset.res],
                        "width": dataset.width, "height": dataset.height, "bands": dataset.count,
                        "descriptions": list(dataset.descriptions),
                        "tags": {key: value for key, value in dataset.tags().items() if key.lower() in {"datetime", "acquisition_date", "date", "platform", "sensor", "polarization"}},
                    })
        except Exception as exc:
            raise HTTPException(status_code=422, detail="A GeoTIFF could not be read for validation.") from exc
    first, second = records
    warnings: list[str] = []
    valid = True
    if not first["crs"] or not second["crs"]:
        valid = False; warnings.append("Both inputs require a declared CRS.")
    elif first["crs"] != second["crs"]:
        valid = False; warnings.append("Pair CRS values differ; reproject to a common CRS before analysis.")
    if first["width"] != second["width"] or first["height"] != second["height"]:
        warnings.append("Raster dimensions differ; verify resampling and grid alignment.")
    if first["bounds"] != second["bounds"]:
        warnings.append("Raster bounds differ; verify that the pair covers the same footprint.")
    if request.mode == "optical-sar":
        warnings.append("Confirm the SAR polarization, incidence geometry, and acquisition timing from source metadata before interpreting fusion output.")
    return {"available": True, "valid": valid, "mode": request.mode, "records": records, "warnings": warnings}


@app.post("/analyze")
def analyze(request: AnalyzeRequest):
    if model is None or preprocess is None or tokenizer is None:
        raise HTTPException(status_code=503, detail="Remote-sensing adapter is unavailable. Train and mount a BigEarthNet checkpoint first.")
    labels = LABELS[request.mode]
    decoded_images = [decode_image(encoded) for encoded in request.images]
    images = [preprocess(image).unsqueeze(0).to(device) for image in decoded_images]
    with torch.no_grad():
        image_features = [model.encode_image(image) for image in images]
        image_features = [feature / feature.norm(dim=-1, keepdim=True) for feature in image_features]
        text_features = model.encode_text(tokenizer([f"a satellite image of {label}" for label in labels]).to(device))
        text_features = text_features / text_features.norm(dim=-1, keepdim=True)
        scores = torch.stack([(feature @ text_features.T).squeeze(0) for feature in image_features]).mean(dim=0)
        ranked = sorted(zip(labels, scores.detach().cpu().tolist()), key=lambda item: item[1], reverse=True)
    evidence = [{"label": label, "score": round(float(score), 4)} for label, score in ranked[:4]]
    change = None
    if len(image_features) == 2:
        change = round(float(1 - torch.nn.functional.cosine_similarity(image_features[0], image_features[1]).item()), 4)
    change_mask = semantic_change_heatmap(decoded_images[0], decoded_images[1]) if request.mode == "bi-temporal" and len(decoded_images) == 2 else None
    return {
        "engine": "bigearthnet-adapted-clip",
        "checkpoint": Path(checkpoint_path).name,
        "query": request.query,
        "evidence": evidence,
        "pairEmbeddingDifference": change,
        "changeMask": change_mask,
        "limitation": "Scores are semantic retrieval evidence from the adapted encoder, not a ground-truth label.",
    }
